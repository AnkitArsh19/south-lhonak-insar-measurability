"""
MintPy SBAS configuration builder and execution wrapper.
"""

from typing import Dict, Any, Optional
from pathlib import Path

def generate_mintpy_template(
    project_name: str,
    output_dir: Path,
    dem_file: Path,
    processor: str = "isce",
    ref_lalo: Tuple[float, float] = (27.915, 88.240),
    coherence_thresh: float = 0.35,
    tropo_method: str = "pyaps", # or 'height_correlation'
    weather_model: str = "ERA5"
) -> Path:
    """
    Generates a reproducible MintPy configuration template file (.txt).
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    cfg_file = output_dir / f"{project_name}_mintpy.cfg"
    
    content = f"""# MintPy configuration for {project_name}
# Automatically generated by IIRS research pipeline

mintpy.load.processor        = {processor}
mintpy.compute.cluster       = local
mintpy.compute.numWorker     = 4

## Reference Point (Stable bedrock)
mintpy.reference.lalo        = {ref_lalo[0]}, {ref_lalo[1]}
mintpy.reference.maskFile    = maskConnComp.h5

## Network Modification
mintpy.network.coherenceBased = yes
mintpy.network.minCoherence   = {coherence_thresh}
mintpy.network.keepMinSpanTree = yes

## Phase Unwrapping Error Correction
mintpy.unwrapError.method    = bridging

## Tropospheric Delay Correction
mintpy.troposphericDelay.method = {tropo_method}
mintpy.troposphericDelay.weatherModel = {weather_model}

## Topographic Residual Correction
mintpy.topographicResidual   = yes

## Output
mintpy.save.hdf5             = yes
"""
    with open(cfg_file, "w", encoding="utf-8") as f:
        f.write(content)
        
    return cfg_file
